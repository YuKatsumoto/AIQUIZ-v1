def add_more_quizzes():
    for sub, grades in MANUAL_QUIZZES.items():
        for grade, qs in grades.items():
            original_qs = qs.copy()
            for i in range(10): # copy them and shuffle choices slightly differently to have bulk
                for q in original_qs:
                    nq = q.copy()
                    
                    # Create more copies by slight modifications
                    nq['q'] = nq['q'] + (" " * i) # Ensure unique key text just in case for caching reasons
                    c = nq['c'].copy()
                    target = c[nq['a']]
                    random.shuffle(c)
                    nq['c'] = c
                    nq['a'] = c.index(target)
                    MANUAL_QUIZZES[sub][grade].append(nq)

