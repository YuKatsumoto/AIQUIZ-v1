import json
import random

def load_bank(path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def save_bank(path, bank):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(bank, f, ensure_ascii=False, indent=2)

def generate_math_4choice(grade, num=20):
    quizzes = []
    for _ in range(num):
        if grade == 1:
            a = random.randint(10, 50)
            b = random.randint(10, 50)
            target = a + b
            q = f"【応用】{a} ＋ {b} はいくつ？"
            exp = f"{a}足す{b}で{target}です。"
        elif grade == 2:
            a = random.randint(3, 9)
            b = random.randint(3, 9)
            c = random.randint(10, 50)
            target = a * b + c
            q = f"【応用】{a} × {b} ＋ {c} はいくつ？"
            exp = f"先に掛け算をして、{a*b}＋{c}＝{target}です。"
        elif grade == 3:
            a = random.randint(100, 999)
            b = random.randint(100, 500)
            target = a - b
            q = f"【応用】{a} － {b} の計算の答えは？"
            exp = f"{a}引く{b}で、答えは{target}です。"
        elif grade == 4:
            a = random.randint(20, 99)
            b = random.randint(11, 49)
            target = a * b
            q = f"【応用】2桁の掛け算：{a} × {b} ＝ ？"
            exp = f"{a} × {b} ＝ {target} です。"
        elif grade == 5:
            a = random.randint(1, 9) * 10
            q = f"【応用】分数の計算：1/2 ＋ 1/4 は？（小数で表すと{0.5+0.25}）"
            target_str = "3/4"
            wrongs = ["1/4", "2/4", "3/8", "4/4", "1/6", "4/8"]
            random.shuffle(wrongs)
            choices = [target_str] + wrongs[:3]
            random.shuffle(choices)
            a_idx = choices.index(target_str)
            quizzes.append({"q": q, "c": choices, "a": a_idx, "exp": "通分して 2/4 ＋ 1/4 ＝ 3/4 です。"})
            continue
        else: # grade 6
            a = random.randint(11, 29)
            target = a * a
            q = f"【応用】面積の計算などでも使う {a} × {a} の答えは？"
            exp = f"{a}を2回掛けると{target}になります。"

        # Generate fake choices
        choices = [str(target)]
        while len(choices) < 4:
            offset = random.choice([-20, -10, -2, -1, 1, 2, 10, 20])
            fake = str(abs(target + offset))
            if fake not in choices:
                choices.append(fake)
        random.shuffle(choices)
        a_idx = choices.index(str(target))
        quizzes.append({"q": q, "c": choices, "a": a_idx, "exp": exp})
    return quizzes

